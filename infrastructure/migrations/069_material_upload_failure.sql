-- 069: 一次失败的上传有了落点 —— **而那个落点同时解开了「重试不了」**。
--
-- ---------------------------------------------------------------------------
-- 运维窗口 2026-09-17 实测：十二份全失败，而本仓没有任何一处会红
-- ---------------------------------------------------------------------------
--
-- 供应商把十二份都拉走了（access.log 十二条 200），然后回了十二条 `cmd=20000`，
-- **认领 0 条**。抓包看到的真面目是：
--
--     code : 500100
--     msg  : 底层客户端业务错误[获取wxCdnInfo失败]
--     data : [ { cmd: 20000, requestId: <我们的>, msgType: 0, msgData: null } ]
--
-- **代码没有做错任何一步**：`msgData` 是 `null`，于是 `upload_result()` 拿不到
-- `fileId`、认领跳过。每一行都按写的执行了 —— **是没有东西可认领**。
--
-- 而那次失败的全部可见形态是：入站答 200、审计行与「有人退群了」共用同一个计数、
-- 目录里那一行**看上去是齐的**（`upload_request_id` 有值，像一次在途的上传，
-- 而它永远不会到达）。运维是靠「认领数一直是 0」发现的，
-- **要查清为什么只能去抓包**。
--
-- ---------------------------------------------------------------------------
-- 两列，一件事
-- ---------------------------------------------------------------------------
--
-- `upload_failed_at` 让失败有形态；`upload_failure_code` 让**下一次**不必抓包。
--
-- **为什么不复用 `status`**：那一列是 `active` / `archived`，说的是「这份资料还用不用」，
-- 与「这一次上传成没成」是两件事。混进去会让归档逻辑与上传重试互相牵制。
--
-- **为什么不只记一个布尔**：运维这次拿到的是 `500100 / 获取wxCdnInfo失败`，
-- 而 `docs/wecom-proxy-cdn-upload-api.md` §2.4 登记着「要问供应商错误码表」——
-- **这是第一条实测到的**。一个布尔会把它扔掉，而下一次换一种失败时，
-- 谁也说不出这两次是不是同一回事。
--
-- ---------------------------------------------------------------------------
-- 它同时解开「重试不了」
-- ---------------------------------------------------------------------------
--
-- `upload_materials.py` 选行的判据是「`upload_request_id` 还空着」。
-- 一次失败之后那一列已经写上了，于是重跑只会说「没有要传的」——
-- 而那个 `requestId` 已经没有任何用处：它对应的上传在供应商那边终结于失败，
-- 不会再有第二条回调。**但它挡着重试。**
--
-- 运维当场卡在这里，而唯一的出路是手改库（把那一列清回 NULL）—— 运维不自行做，
-- 也不该做。有了 `upload_failed_at`，选行判据可以写成
-- 「没传过 **或者** 传失败了」，**不需要任何人碰数据**。
--
-- ---------------------------------------------------------------------------
-- 授权
-- ---------------------------------------------------------------------------
--
-- * `fastagent_ingress`：写这两列（它是唯一知道失败发生了的角色），
--   外加 `upload_failed_at` 的 `SELECT` —— 认领那句 `WHERE` 要读它
--   （`067` 少发一列的教训：`WHERE` 里的列要的是 `SELECT` 权限，
--   而缺它的症状是整件事不工作，且报文不提是哪一列）；
-- * `fastagent_app`：读这两列（导入/上传脚本按它们选行，运维按它们排障）
--   并写 `upload_request_id`（重试时要覆盖它）—— 那一列的 `UPDATE` 它本来就有。
--
-- **`fastagent_worker` 一列都不给**：发送那一刻只关心「传成了没有」，
-- 而那由 `provider_file_id` 答（`068` 已经给了）。失败的原因与它无关。
--
-- ---------------------------------------------------------------------------
-- 可逆
-- ---------------------------------------------------------------------------
--
-- 两列可空无默认，既有行全部为 NULL（语义：没失败过）。授权只增不减。

ALTER TABLE materials
    ADD COLUMN upload_failed_at timestamptz,
    ADD COLUMN upload_failure_code text
        CHECK (upload_failure_code IS NULL
               OR length(upload_failure_code) BETWEEN 1 AND 200);

COMMENT ON COLUMN materials.upload_failed_at IS
    '这一行最后一次上传失败的时点。NULL = 没失败过。'
    '**它与 upload_request_id 一起读**：两个都有值 = 传过且失败了（可重试）；'
    '只有 request_id = 在途；都没有 = 还没传过。';

COMMENT ON COLUMN materials.upload_failure_code IS
    '供应商那次回的 code 与 msg（截断到 200 字）。'
    '实测第一条：500100 底层客户端业务错误[获取wxCdnInfo失败]（2026-09-17）。'
    '记原文而不是映射成本仓的词：这一族的错误码表供应商没给，'
    '而把没见过的码映射成已知词表是猜。';

GRANT SELECT (upload_failed_at) ON materials TO fastagent_ingress;
GRANT UPDATE (upload_failed_at, upload_failure_code) ON materials TO fastagent_ingress;

GRANT SELECT (upload_failed_at, upload_failure_code) ON materials TO fastagent_app;

INSERT INTO schema_migrations(version) VALUES ('069_material_upload_failure')
ON CONFLICT (version) DO NOTHING;
