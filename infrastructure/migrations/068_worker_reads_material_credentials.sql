-- 068: 发送那一刻，worker 要拿得到那对密钥。
--
-- ---------------------------------------------------------------------------
-- 本条线的第三处权限改动，而这次拿到密钥**读权**的是 worker
-- ---------------------------------------------------------------------------
--
-- `/msg/sendFile` 的必填是 `guid` / `fileId` / `fileSize` / `fileMd5` /
-- `filename` / `toId`，外加条件必填的 `fileAesKey`（大文件可空，否则必填）。
-- 派发一行文件消息的是 worker，所以那一刻它得读得到这几列。
--
-- 三处权限改动各自拿到的不是同一样东西，这一点值得并排看：
--
-- | 迁移 | 角色 | 拿到什么 | 拿不到什么 |
-- |---|---|---|---|
-- | `065` | `fastagent_app` | 目录的 `INSERT`（导入脚本） | —— |
-- | `066` | `fastagent_app` | 十五列的 `SELECT` | **那两列凭据** |
-- | `067` | `fastagent_ingress` | 四列 `UPDATE` + 四列 `SELECT` | **读回那两列凭据** |
-- | `068` | `fastagent_worker` | **读那两列凭据** | 一切写操作 |
--
-- **只有 worker 读得到密钥，而它一个字都写不了。** 入站写得进读不回来，
-- worker 读得到写不进去 —— 两边各自只拿了自己那一半，谁都不是「完全访问」。
--
-- ---------------------------------------------------------------------------
-- 为什么不把密钥放进 `outbox_messages.content` 让 worker 免授权
-- ---------------------------------------------------------------------------
--
-- 那是这一批最容易走的一条近路：决策时把四个字段拼进 content，派发时照着发，
-- worker 一条授权都不用加。**不走它，理由与 `inbound.py` 拒绝把
-- `fileAesKey` 写进 `inbox_events.content` 逐字同源** ——
-- 那会把凭据复制进另一张表，而那张表的读面比 `materials` 宽得多
-- （`058` 起 `fastagent_app` 就读得到出站行，消息页也读它）。
--
-- 一行出站消息带的是**引用**，密钥在发送那一刻才从目录里取。
--
-- ---------------------------------------------------------------------------
-- 列清单：为什么是这几列
-- ---------------------------------------------------------------------------
--
-- * `tenant_id` —— RLS 的策略表达式读它；
-- * `id` / `slug` / `version` —— 解析 `asset:<slug>` 要按 slug 找**当前那一版**
--   （ADR-0130 §二.2：profile 声明 slug 不声明版本，发送时解析当前版），
--   而排障要答得出「发出去的是哪一行」；
-- * `status` / `archived_at` —— 归档掉的版本不该被发出去，而那道闸在 worker 侧；
-- * `filename` —— `sendFile` 的必填之一；
-- * 四列 `provider_*` —— 其余四个必填字段。
--
-- **不给的**：`source_url`（那是给供应商去拉的地址，发送时用不着它）、
-- `byte_size`（`sendFile` 要的是供应商那边的 `provider_file_size`，
-- 不是我们自己算的那个 —— 两个数描述同一份文件的两侧，见 `066`）、
-- `content_hash`、`upload_request_id`（上传那条线的东西）。
--
-- ---------------------------------------------------------------------------
-- 可逆
-- ---------------------------------------------------------------------------
--
-- 没有 DDL，只有一条 `GRANT`。撤销就是一条 `REVOKE`，
-- 代价是文件发不出去（发送会以权限错失败，而那会变成一条失败回执，不是崩溃）。

GRANT SELECT (
    tenant_id, id, slug, version, status, archived_at, filename,
    provider_file_id, provider_file_aes_key, provider_file_md5, provider_file_size
) ON materials TO fastagent_worker;

