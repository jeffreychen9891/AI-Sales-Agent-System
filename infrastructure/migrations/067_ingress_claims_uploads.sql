-- 067: 入站侧认领上传结果 —— **写得进那四列，而密钥读不回来**。
--
-- ---------------------------------------------------------------------------
-- 用户 2026-09-16 裁定：ingress 直接认领
-- ---------------------------------------------------------------------------
--
-- 上传结果走 `cmd=20000` 回来，靠 `requestId` 与发起方关联
-- （`docs/wecom-proxy-cdn-upload-api.md`：「回调通知中的 requestId 会与
-- 同步响应中的 requestId 等同」）。收到它的是 ingress。
--
-- 两条路摆过：ingress 直接写目录，或者 ingress 只落一行、另一步搬。
-- 用户选前者。所以这一条发的是本条线的**第二处权限改动** ——
-- 而它动的是**面向公网的那个服务**，所以每一半都写清了边界在哪。
--
-- ---------------------------------------------------------------------------
-- 它**写得进密钥，却读不回来**，这是有意的
-- ---------------------------------------------------------------------------
--
-- `UPDATE` 那四列里有 `provider_file_aes_key`，而下面的 `SELECT` **不发那两列凭据**
-- （`provider_file_aes_key` / `provider_file_md5`）。于是 `fastagent_ingress`：
--
-- | 它能做的 | 它做不到的 |
-- |---|---|
-- | 把回调带回的密钥写进那一行 | **把任何一行的密钥读出来** |
-- | 按 `upload_request_id` 找到是哪一行 | 读 slug / 文件名 / 地址 / 哈希 |
-- | 看出那一行认领过没有（`provider_file_id`） | —— |
--
-- 这不是一句注释能保证的事，PostgreSQL 会保证它：列级 `UPDATE` 与列级 `SELECT`
-- 是两份独立的授权。**`066` 把这张表改成列级正是为了今天** ——
-- 那时它还是表级 `SELECT`，这一条一发，ingress 连带就读到了全表。
--
-- ---------------------------------------------------------------------------
-- `SELECT` 为什么非发不可（不是顺手多给的）
-- ---------------------------------------------------------------------------
--
-- `UPDATE ... WHERE upload_request_id = $1` 的 `WHERE` 要读那一列，
-- 而 PostgreSQL 对 `WHERE` 里出现的列要的是 **`SELECT` 权限**，不是 `UPDATE`。
-- 少发这一条，认领会以 `permission denied` 失败 —— **而那是在真实回调回来时**。
--
-- `tenant_id` 同理（RLS 的策略表达式读它），`id` 是给审计与排障留一个坐标。
--
-- **`provider_file_id` 也在 `WHERE` 里**：认领带 `AND provider_file_id IS NULL`
-- 作幂等那一半（供应商会重投回调）。所以它既要 `UPDATE` 也要 `SELECT` ——
-- 而它**是句柄不是密钥**（`066` 已经把它发给了 `fastagent_app` 的读路由）。
--
-- **这一列是本条用例抓出来的，不是想出来的**：第一版只发了三列，
-- 整格门禁里那条「真跑一次」的用例以 `permission denied for table materials`
-- 红在写那一段。**换句话说，缺这条授权的症状是认领整个不工作** ——
-- 而如果没有那条用例，它会在第一个真实回调回来时才出现。
--
-- ---------------------------------------------------------------------------
-- RLS 照旧管着它
-- ---------------------------------------------------------------------------
--
-- `053` 的 `materials_tenant_isolation` 对 `fastagent_ingress` 一样生效：
-- ingress 的事务带着 `app.tenant_id`（来自回调地址解析出的绑定），
-- 所以**一个租户的回调认领不到另一个租户的行** —— 授权管「哪几列」，
-- RLS 管「哪几行」，两层各管各的。
--
-- ---------------------------------------------------------------------------
-- 可逆
-- ---------------------------------------------------------------------------
--
-- 没有 DDL，只有两条 `GRANT`。撤销就是对应的两条 `REVOKE`，
-- 代价是认领停摆（已认领的行不受影响）。**不新增表、不改列、不删任何东西。**

GRANT SELECT (tenant_id, id, upload_request_id, provider_file_id)
    ON materials TO fastagent_ingress;

GRANT UPDATE (
    provider_file_id, provider_file_aes_key, provider_file_md5, provider_file_size
) ON materials TO fastagent_ingress;

INSERT INTO schema_migrations(version) VALUES ('067_ingress_claims_uploads')
ON CONFLICT (version) DO NOTHING;
